USE HiX_LS

DROP TABLE IF EXISTS #OM
GO

-- #region Opname Mutaties (OM)
SELECT

	-- Patient
		OO.PATIENTNR AS 'Patientnummer'
		,oo.BEHCODE
	,	FLOOR(DATEDIFF(day, CAST(PP.GEBDAT AS date), CAST(RP_OO.STARTDATE AS date)) / 365.25) AS 'Leeftijd bij Opname'
	,	IIF(FLOOR(DATEDIFF(day, CAST(PP.GEBDAT AS date), CAST(RP_OO.STARTDATE AS date)) / 365.25) >= 18, 'Volwassen', 'Kind') AS 'Leeftijdscategorie'
	,	PP.GESLACHT AS 'Geslacht'
	,	CONVERT(DATE, PP.GEBDAT) AS 'Geboortedatum'
	,	IIF(OB.OVERLEDEN = 1, 'Ja', 'Nee') AS 'Tijdens opname overleden'

	-- Opname
	,	OO.PLANNR AS 'Opname ID'
	,	OO.WORKFLOWSTATUS AS 'Opname Status Code'
	,	ORDERCOM_ORDSTAT.OMSCHR AS 'Opname Status'
	,	IIF(OO.SPOED = 1 OR OO.OPNURGCODE = '1', 1, 0) AS 'Is Spoed?'
	,	OO.SPECIALISM AS 'Opname Specialisme'
	,	OO.BEHINFO AS 'Behandelinformatie'
	,	OO.BEHCODE AS 'Behandel Code'
	,	OBC.OMSCHR AS 'Behandel Omschrijving'
	,	OO.OPNTYPE AS 'Opnametype Code'
	,	OOT.OMSCHR AS 'Opnametype Omschrijving'
	,	OOT.CATEGORIE AS 'Opname Categorie'
	,	CASE	
			WHEN OOT.CATEGORIE = 'D' THEN 'Dagbehandeling'
			WHEN OOT.CATEGORIE = 'K' THEN 'Klinische behandeling'
			WHEN OOT.CATEGORIE = 'O' THEN 'Observatie'
			WHEN OOT.CATEGORIE = 'P' THEN 'Poliklinische behandeling'
			ELSE 'Onbekend'
		END AS 'Opname Categorie Omschrijving'

	-- Opname Datum en Tijd
	,	CONVERT(
			DATE,	
			CASE	
				WHEN OO.WORKFLOWSTATUS IN ('DT000097', 'DT000099') THEN RP_OO.STARTDATE
				WHEN OO.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN RP_OO.STARTDATEPLAN
				ELSE NULL 
			END
		) AS 'Opnamedatum'
	,	CASE
			WHEN OO.WORKFLOWSTATUS IN ('DT000097', 'DT000099') THEN RP_OO.STARTTIME
			WHEN OO.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN RP_OO.STARTTIMEPLAN
			ELSE NULL 
		END AS 'Opnametijd'
	,	CONVERT(
			DATETIME,
			CASE WHEN OO.WORKFLOWSTATUS IN ('DT000097', 'DT000099') THEN RP_OO.STARTDATE + RP_OO.STARTTIME
				WHEN OO.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN RP_OO.STARTDATEPLAN + COALESCE(NULLIF(RP_OO.STARTTIMEPLAN, ''), '00:00')
				ELSE NULL 
			END
		) AS 'Opnamedatumtijd'

	-- Medisch Klaar Datum en Tijd
	,	OO.MEDISCHKLAAR AS 'Medisch Klaar'
	,	IIF(OO.MEDISCHKLAAR = 1, CONVERT(DATE, OO.MEDISCHKLAARDAT), NULL) AS 'Medisch Klaar Datum'
	,	IIF(OO.MEDISCHKLAAR = 1, OO.MEDISCHKLAARTIJD, NULL) AS 'Medisch Klaar Tijd'
	,	IIF(OO.MEDISCHKLAAR = 1, CONVERT(DATETIME, OO.MEDISCHKLAARDAT + OO.MEDISCHKLAARTIJD), NULL) AS 'Medisch Klaar DatumTijd'

	-- Ontslag Datum en Tijd
	,	CONVERT(
			DATE,
			CASE
				WHEN OO.WORKFLOWSTATUS IN ('DT000099') THEN RP_OO.ENDDATE
				WHEN OO.WORKFLOWSTATUS IN ('DT000097') THEN COALESCE(RP_OO.ENDDATEPROVISIONAL, RP_OO.ENDDATE, RP_OO.ENDDATEPLAN, '29991231')
				WHEN OO.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN COALESCE(RP_OO.ENDDATEPLAN, '29991231')
				ELSE NULL 
			END
		) AS 'Ontslagdatum'
	,	CASE
			WHEN OO.WORKFLOWSTATUS IN ('DT000099') THEN RP_OO.ENDTIME
			WHEN OO.WORKFLOWSTATUS IN ('DT000097') THEN COALESCE(NULLIF(RP_OO.ENDTIMEPROVISIONAL, ''), NULLIF(RP_OO.ENDTIME, ''), NULLIF(RP_OO.ENDTIMEPLAN, ''), '23:59')
			WHEN OO.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN COALESCE(NULLIF(RP_OO.ENDTIMEPLAN, ''), '23:59')
			ELSE NULL
		END AS 'Ontslagtijd'
	,	CONVERT(
			DATETIME,
			CASE	
				WHEN OO.WORKFLOWSTATUS IN ('DT000099') THEN RP_OO.ENDDATE + RP_OO.ENDTIME
				WHEN OO.WORKFLOWSTATUS IN ('DT000097') THEN COALESCE(RP_OO.ENDDATEPROVISIONAL, RP_OO.ENDDATE, RP_OO.ENDDATEPLAN, '29991231') + COALESCE(NULLIF(RP_OO.ENDTIMEPROVISIONAL, ''), NULLIF(RP_OO.ENDTIME, ''), NULLIF(RP_OO.ENDTIMEPLAN, ''), '23:59')
				WHEN OO.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN COALESCE(RP_OO.ENDDATEPLAN, '29991231') + COALESCE(NULLIF(RP_OO.ENDTIMEPLAN, ''), '23:59')
				ELSE NULL
			END
		) AS 'Ontslagdatumtijd'

	-- Bekijken!
	,	CONVERT(
			FLOAT,
			CASE 
				WHEN OO.WORKFLOWSTATUS = 'DT000099'
				THEN ROUND(DATEDIFF(mi, RP_OO.STARTDATE + RP_OO.STARTTIME, RP_OO.ENDDATE + RP_OO.ENDTIME) / (24.0 * 60.0), 3)
				ELSE ROUND(DATEDIFF(mi, RP_OO.STARTDATE + RP_OO.STARTTIME, GETDATE()) / (24.0 * 60.0), 3)
			END
		) AS 'Aantal dagen opgenomen'

	-- Opname Herkomst en Bestemming
	,	OO.HERKOMST AS 'Opname Herkomst ID'
	,	OH.OMSCHR AS 'Herkomst'
	,	OO.BESTEMMING AS 'Bestemming ID'
	,	OB.OMSCHR AS 'Bestemming'

	-- Opname Mutatie
	,	OM.MUTATIEID AS 'Opnamemutatie id'
	,	OM.MUTPOSITIE AS 'Opnamemutatie Positie'
	,	CASE	
			WHEN OM.MUTPOSITIE = 'F' THEN 'First'
			WHEN OM.MUTPOSITIE = 'M' THEN 'Mutatie' 
			WHEN OM.MUTPOSITIE = 'O' THEN 'Only'
			WHEN OM.MUTPOSITIE = 'L' THEN 'Last'
			ELSE NULL 
		END AS 'Opnamemutatie Positie Omschrijving'
	,	OM.AFDELING AS 'Opnamemutatie Afdeling'
	,	CONVERT(
			DATE,
			CASE	
				WHEN OM.WORKFLOWSTATUS IN ('DT000097', 'DT000099') THEN RP_OM.STARTDATE
				WHEN OM.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN RP_OM.STARTDATEPLAN
				ELSE NULL 
			END
		) AS 'Opnamemutatie begindatum'
	,	CASE
			WHEN OM.WORKFLOWSTATUS IN ('DT000097', 'DT000099') THEN RP_OM.STARTTIME
			WHEN OM.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN RP_OM.STARTTIMEPLAN
			ELSE NULL 
		END AS 'Opnamemutatie begintijd'
	,	CONVERT(
			DATETIME,
			CASE	
				WHEN OM.WORKFLOWSTATUS IN ('DT000097', 'DT000099') THEN RP_OM.STARTDATE + RP_OM.STARTTIME
				WHEN OM.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN RP_OM.STARTDATEPLAN + COALESCE(NULLIF(RP_OM.STARTTIMEPLAN, ''), '00:00')
				ELSE NULL 
			END
		) AS 'Opnamemutatie begindatumtijd'
	,	CONVERT(
			DATE,
			CASE	
				WHEN OM.WORKFLOWSTATUS IN ('DT000099') THEN RP_OM.ENDDATE
				WHEN OM.WORKFLOWSTATUS IN ('DT000097') THEN IIF(OM.MUTPOSITIE IN ('F', 'M'), RP_OM.ENDDATE, COALESCE(RP_OM.ENDDATEPROVISIONAL, RP_OM.ENDDATEPLAN, '29991231'))
				WHEN OM.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN COALESCE(RP_OM.ENDDATEPLAN, '29991231')
				ELSE NULL 
			END
		) AS 'Opnamemutatie einddatum'
	,	CASE	
			WHEN OM.WORKFLOWSTATUS IN ('DT000099') THEN RP_OM.ENDTIME 
			WHEN OM.WORKFLOWSTATUS IN ('DT000097') THEN IIF(OM.MUTPOSITIE IN ('F', 'M'), RP_OM.ENDTIME, COALESCE(NULLIF(RP_OM.ENDTIMEPROVISIONAL, ''), NULLIF(RP_OM.ENDTIMEPLAN, ''), '23:59'))
			WHEN OM.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN COALESCE(NULLIF(RP_OM.ENDTIMEPLAN, ''), '23:59')
			ELSE NULL
		END AS 'Opnamemutatie eindtijd'
	,	CONVERT(
			DATETIME,
			CASE	
				WHEN OM.WORKFLOWSTATUS IN ('DT000099') THEN RP_OM.ENDDATE + RP_OM.ENDTIME 
				WHEN OM.WORKFLOWSTATUS IN ('DT000097') THEN IIF(OM.MUTPOSITIE IN ('F', 'M'), RP_OM.ENDDATE, COALESCE(RP_OM.ENDDATEPROVISIONAL, RP_OM.ENDDATEPLAN, '29991231')) + IIF(OM.MUTPOSITIE IN ('F', 'M'), RP_OM.ENDTIME, COALESCE(NULLIF(RP_OM.ENDTIMEPROVISIONAL, ''), NULLIF(RP_OM.ENDTIMEPLAN, ''), '23:59'))
				WHEN OM.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN COALESCE(RP_OM.ENDDATEPLAN, '29991231') + COALESCE(NULLIF(RP_OM.ENDTIMEPLAN, ''), '23:59')
				ELSE NULL 
			END 
		) AS 'Opnamemutatie einddatumtijd'

	-- Locatie
	,	OM.WARDLOCID AS 'Afdeling ID'
	,	WARD.SHORTDESCR AS 'Afdeling Korte Omschrijving'
	,	WARD.DESCRIPTION AS 'Afdeling Omschrijving'
	,	ROOM.LOCATIONID AS 'Kamer ID'
	,	ROOM.DESCRIPTION AS 'Kamer Omschrijving'
	,	BED.LOCATIONID AS 'Bed ID'
	,	BED.DESCRIPTION AS 'Bed Omschrijving'

	-- Behandelaar
	,	OM.BEHANDELAA AS 'Behandelend Arts Code'
	,	CASE 
			WHEN CAU.PONSNAAM = '' THEN 
				CASE 
					WHEN CAU.ACHTERNAAM = ''
					THEN LTRIM(RTRIM(CAU.MEISJESNAA)) COLLATE SQL_Latin1_General_CP1_CI_AS
					ELSE LTRIM(RTRIM(CAU.ACHTERNAAM)) COLLATE SQL_Latin1_General_CP1_CI_AS
				END
			ELSE LTRIM(RTRIM(CAU.PONSNAAM)) 
		END AS 'Behandelaar Naam'
	,	CAU.ARTSTYPE AS 'Behandelaar Artstype'
	,	CATU.OMSCHR AS 'Behandelaar Artstype Omschrijving'
	,	CAU.SPECIALISM AS 'Behandelaar Arts Specialisme'
	,	CAU.ZORGVSOORT AS 'Behandelaar Arts Zorgverlenersoort'
	,	CUI.ZORGVCODE AS 'Behandelaar Zorgverlener Code (AGB)'
	,	CAU.instantie AS 'Behandelaar Arts Instantie Werkzaam Code'
	,	CUI.NAAM AS 'Behandelaar Arts Instantie Werkzaam Naam'


-- Mutaties van de opname
FROM OPNAME_OPNMUT AS OM

-- Informatie over de opname
LEFT JOIN OPNAME_OPNAME AS OO
	ON OO.PLANNR = OM.PLANNR

-- Patient
LEFT JOIN HiX_LS.dbo.PATIENT_PATIENT AS PP
	ON OO.PATIENTNR = PP.PATIENTNR

-- Bed
LEFT JOIN CSZISLIB_LOCATION AS BED
	on BED.LOCATIONID = OM.BEDLOCID

-- Kamer
LEFT JOIN CSZISLIB_LOCATION AS ROOM
	on ROOM.LOCATIONID = OM.ROOMLOCID

-- Afdeling
LEFT JOIN HiX_LS.dbo.CSZISLIB_LOCATION AS WARD
	ON WARD.LOCATIONID = OM.WARDLOCID

-- Datum en tijd van OPNAME_OPNMUT
LEFT JOIN HiX_LS.dbo.RP_PLANOBJECT AS RP_OM
	ON RP_OM.LINKEDOBJECTCLASSID = 'OPNAME_OPNMUT' 
	AND RP_OM.LINKEDOBJECTID = OM.MUTATIEID

-- Datum en tijd uit OPNAME_OPNAME
LEFT JOIN HiX_LS.dbo.RP_PLANOBJECT AS RP_OO
	ON RP_OO.LINKEDOBJECTCLASSID = 'OPNAME_OPNAME' 
	AND RP_OO.LINKEDOBJECTID = OO.PLANNR

-- Order
LEFT JOIN HiX_LS.dbo.ORDERCOM_ORDSTAT 
	ON ORDERCOM_ORDSTAT.STATUSCODE = OO.WORKFLOWSTATUS

-- Behandelcode
LEFT JOIN Hix_LS.dbo.OPNAME_BEHCODE AS OBC
	ON OBC.CODE = OO.BEHCODE

-- Opnametype Omschrijving
LEFT JOIN Hix_LS.dbo.OPNAME_OPNTYPE1 AS OOT
	ON OOT.CODE = OO.OPNTYPE

-- Bestemming
LEFT JOIN Hix_LS.dbo.OPNAME_BESTEM AS OB
	ON OB.CODE = OO.BESTEMMING

-- Herkomst
LEFT JOIN Hix_LS.dbo.OPNAME_HERKOMST AS OH
	ON OH.CODE = OO.HERKOMST

-- Informatie over de uitvoerder ophalen
LEFT JOIN CSZISLIB_ARTS AS CAU 
	ON OM.BEHANDELAA = CAU.ARTSCODE

-- Informatie over de uitvoerende instantie ophalen.
LEFT JOIN CSZISLIB_TBI AS CUI
	ON CAU.instantie = CUI.TBICODE

-- Uitvoerend Arts type omschrijving ophalen.
LEFT JOIN CSZISLIB_ARTSTYPE AS CATU
	ON CATU.CODE = CAU.ARTSTYPE

-- Filters
WHERE 1 = 1 
	AND OM.WORKFLOWSTATUS IN (
			'DT000099' -- Ontslagen
		,	'DT000097' -- Opgenomen
	) 

	AND CONVERT(
			DATE,	
			CASE	
				WHEN OO.WORKFLOWSTATUS IN ('DT000097', 'DT000099') THEN RP_OO.STARTDATE
				WHEN OO.WORKFLOWSTATUS IN ('DT000075', 'DT000101', 'DT000119') THEN RP_OO.STARTDATEPLAN
				ELSE NULL 
			END
		) BETWEEN '2025-01-01' AND GETDATE() -- Opnamedatum tussen 2022-01-01 en vandaag

	AND OO.BEHINFO LIKE '%adjuvant%'

-- #endregion
