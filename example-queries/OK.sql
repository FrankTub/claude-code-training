USE HIX_LS

SELECT
		OOI.OPNAMENR AS 'Opname Nummer'
	,	OOI.ZKH_NR AS 'Patient Nummer'
	,	CONVERT(DATE, PP.GEBDAT) AS 'Patient Geboortedatum'
	,	FLOOR(DATEDIFF(mm, PP.GEBDAT, OOI.OPERATIE_D) / 12) AS 'Leeftijd Ten Tijde van OK'
	,	OOI.OPERATIENR AS 'Operatie Nummer'
	,	CONVERT(DATE, OOI.OPERATIE_D) AS 'Operatie Datum'
	,	LC.SHORTDESCR AS 'Operatie Kamer'
	,	OOI.ZKHLOCCODE AS 'Ziekenhuislocatie Code'
	,	OOI.INDICATIE AS 'Operatie Indicatie'
	,	OOI.LOKALISATIE AS 'Operatie Lokalisatie'
	,	OOV.VER_CODE AS 'Operatie Verrichting Code'
	,	OVC.OMSCHR AS 'Operatie Verrichting'
	,	OOV.AANTAL AS 'Operatie Verrichting Aantal'
	,	OOI.VOORBERMEMO AS 'Operatie Memo'
	,	OOV.DBCNUMMER AS 'Operatie DBC Nummer'
	,	ED.SPECIALISM AS 'Operatie DBC Specialisme'
	,	ED.ZORGTYPE AS 'Operatie DBC Zorgtype'
	,	EZT.OMSCHRIJV AS 'Operatie DBC Zorgtype omschrijving'
	,	ED.ZORGVRAAG AS 'Operatie DBC Zorgvraag'
	,	EZV.OMSCHRIJV AS 'Operatie DBC Zorgvraag omschrijving'
	,	ED.HOOFDDIAG AS 'Operatie DBC Diagnose'
	,	DIAO.OMSCHRIJV AS 'Operatie DBC Diagnose omschrijving'
	,	CONVERT(DATE, ED.BEGINDAT) AS 'Operatie DBC Begin Datum'
	,	CONVERT(DATE, ED.EINDDAT) AS 'Operatie DBC Einde Datum'
	,	CAA.ARTSCODE AS 'Aanvrager Arts Code'
	,	CASE 
			WHEN CAA.PONSNAAM = '' 
			THEN 
				CASE 
					WHEN CAA.ACHTERNAAM = ''
					THEN LTRIM(RTRIM(CAA.MEISJESNAA)) COLLATE SQL_Latin1_General_CP1_CI_AS
					ELSE LTRIM(RTRIM(CAA.ACHTERNAAM)) COLLATE SQL_Latin1_General_CP1_CI_AS 
				END 
			ELSE LTRIM(RTRIM(CAA.PONSNAAM)) 
		END AS 'Aanvrager Naam'
	,	CAA.SPECIALISM AS 'Aanvrager Specialisme'
	,	CAU.ARTSCODE AS 'Uitvoerder Artscode'
	,	CASE 
			WHEN CAU.PONSNAAM = '' 
			THEN 
				CASE 
					WHEN CAU.ACHTERNAAM = ''
					THEN LTRIM(RTRIM(CAU.MEISJESNAA)) COLLATE SQL_Latin1_General_CP1_CI_AS
					ELSE LTRIM(RTRIM(CAU.ACHTERNAAM)) COLLATE SQL_Latin1_General_CP1_CI_AS 
				END 
			ELSE LTRIM(RTRIM(CAU.PONSNAAM)) 
		END AS 'Uitvoerder Naam'
	,	CAU.SPECIALISM AS 'Uitvoerder Specialisme'
	,	ANESTARTS.ARTSCODE AS 'Anesthesist Artscode'
	,	CASE 
			WHEN ANESTARTS.PONSNAAM = '' 
			THEN 
				CASE 
					WHEN ANESTARTS.ACHTERNAAM = ''
					THEN LTRIM(RTRIM(ANESTARTS.MEISJESNAA)) COLLATE SQL_Latin1_General_CP1_CI_AS
					ELSE LTRIM(RTRIM(ANESTARTS.ACHTERNAAM)) COLLATE SQL_Latin1_General_CP1_CI_AS 
				END 
			ELSE LTRIM(RTRIM(ANESTARTS.PONSNAAM)) 
		END AS 'Anesthesist Naam'
	,	ANESTARTS.SPECIALISM AS 'Anesthesist Specialisme'
	,	FORMAT(OOI.T_AFDBEL / 60, '00') + ':' + FORMAT(OOI.T_AFDBEL % 60, '00') AS 'Bellen afdeling'
	,	FORMAT(OOI.T_NAARAFD / 60, '00') + ':' + FORMAT(OOI.T_NAARAFD % 60, '00') AS 'Naar afdeling'
	,	CASE 
			WHEN OOI.T_AFDBEL = 0 
			THEN 0
			WHEN OOI.T_NAARAFD >= OOI.T_AFDBEL 
			THEN CONVERT(NVARCHAR(5), OOI.T_NAARAFD - OOI.T_AFDBEL) 
			ELSE 0 -- Of een ANDere gewenste weergave voor negatieve tijdsverschillen
		END AS 'Tijdverschil in minuten'
	,	OPN.Afdeling AS 'Opname afdeling'
	,	OPN.BEHCODE AS 'Opname Behandelcode'

FROM [HiX_LS].[dbo].[OK_OKINFO] AS OOI

LEFT OUTER JOIN [HiX_LS].[dbo].[PATIENT_PATIENT] AS PP
	ON PP.PATIENTNR = OOI.ZKH_NR

LEFT OUTER JOIN [HiX_LS].[dbo].[OK_OKVER] AS OOV
	ON OOV.OPERATIENR = OOI.OPERATIENR

LEFT OUTER JOIN [HiX_LS].[dbo].[OK_VERCODES] AS OVC 
	ON OVC.CODE = OOV.VER_CODE 
	AND OVC.VERVALLEN <> '1'

LEFT OUTER JOIN [HiX_LS].[dbo].[CSZISLIB_ARTS] AS CAU
	ON CAU.ARTSCODE = OOI.SNIJD_SPEC

LEFT OUTER JOIN [HiX_LS].[dbo].[CSZISLIB_ARTS] AS CAA
	ON CAA.ARTSCODE = OOI.AANVR_SPEC

LEFT JOIN [HiX_LS].[dbo].[OK_OKANAEST] AS ANEST 
	ON ANEST.OPERATIENR = OOI.OPERATIENR

LEFT JOIN [HiX_LS].[dbo].[CSZISLIB_ARTS] AS ANESTARTS 
	ON ANESTARTS.ARTSCODE = ANEST.ANAESTHESI -- Naam gegevens anesthesist

LEFT OUTER JOIN [HiX_LS].[dbo].[EPISODE_DBCPER] AS ED
	ON ED.DBCNUMMER = OOV.DBCNUMMER

OUTER APPLY (
	SELECT TOP 1 EDI.OMSCHRIJV 
	FROM [HiX_LS].[dbo].[EPISODE_DIAG] AS EDI
	WHERE 1=1
		AND EDI.CODE = ED.HOOFDDIAG 
		AND EDI.SPECIALISM = ED.SPECIALISM
		AND ISNULL(EDI.DATUM, CONVERT(DATE, '1900-01-01')) <= ISNULL(ED.BEGINDAT, '1900-01-01')
		AND ISNULL(EDI.EINDDATUM, CONVERT(DATE, '9999-12-31')) >= ISNULL(ED.BEGINDAT, '9999-12-31')
) DIAO

OUTER APPLY (
	SELECT TOP 1 *
	FROM [HiX_LS].[dbo].[EPISODE_ZORGTYPE] AS EZT
	WHERE 1=1
		AND EZT.Code = ED.ZORGTYPE 
		AND ISNULL(EZT.BEGINDAT, '1900-01-01') <= ISNULL(ED.BEGINDAT, '1900-01-01')
		AND ISNULL(EZT.EINDDAT, '9999-12-31') >= ISNULL(ED.BEGINDAT, '9999-12-31')
	ORDER BY EZT.BEGINDAT DESC
) EZT

OUTER APPLY (
	SELECT TOP 1 *
	FROM [HiX_LS].[dbo].[EPISODE_ZORGVRAA] AS EZV
	WHERE 1=1
		AND EZV.Code = ED.ZORGVRAAG 
		AND EZV.SPECIALISM = ED.SPECIALISM 
		AND ISNULL(EZV.DATUM, '1900-01-01') <= ISNULL(ED.BEGINDAT, '1900-01-01')
		AND ISNULL(EZV.EINDDATUM, '9999-12-31') >= ISNULL(ED.BEGINDAT, '9999-12-31')
	ORDER BY  EZV.DATUM DESC
) EZV

LEFT JOIN HiX_LS.dbo.RP_PLANOBJECT AS [RP] 
	ON RP.LINKEDOBJECTCLASSID = 'OK_OKINFO' 
	AND RP.LINKEDOBJECTID = OOI.OPERATIENR

LEFT JOIN HiX_LS.dbo.CSZISLIB_LOCATION AS [LC] 
	ON LC.LOCATIONID = RP.LOCATIONID

OUTER APPLY (
	SELECT TOP 1 
			WARD.SHORTDESCR AS [Afdeling]
		,	BEHCODE
	FROM HiX_LS.dbo.OPNAME_OPNMUT AS [OM]
	JOIN HiX_LS.dbo.OPNAME_OPNAME AS [OO] 
		ON OO.PLANNR = OM.PLANNR
	JOIN HiX_LS.dbo.RP_PLANOBJECT AS [RP] 
		ON RP.LINKEDOBJECTCLASSID = 'OPNAME_OPNMUT'
		AND RP.LINKEDOBJECTID = OM.MUTATIEID
	JOIN HiX_LS.dbo.CSZISLIB_LOCATION [WARD] 
		ON WARD.LOCATIONID = OM.WARDLOCID
	WHERE 1=1
		AND OO.PLANNR = OOI.OPNAMENR
		AND OO.ANNUDAT IS NULL
	ORDER BY RP.STARTDATE ASC
) OPN

WHERE 1=1
	AND OOI.OPERATIE_D >= ' 2025-01-01'
	AND OOI.VERVALLEN = 0
	AND OVC.OMSCHR LIKE '%sigmoid%'
	
ORDER BY OOI.ZKH_NR, OOI.OPERATIENR
